function applyMap(
  html: string,
  path: string,
  locale: Locale,
  map: Record<string, BatchConfig>,
): string {
  const row = map[normalizePath(path)];
  if (!row) return html;
  let next = html;
  next = upsertArticleLead(next, row.lead(locale));
  next = upsertArticleFaq(next, row.faq(locale), row.postMarker);
  return next;
}

/** Batch6 — Hebrew business/agency reading UX rollout. */
export function applyArticleBatch6Enrichment2026(html: string, path: string, locale: Locale): string {
  if (locale !== "he") return html;
  return applyMap(html, path, locale, BATCH6_HE);
}

